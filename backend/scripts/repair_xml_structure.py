#!/usr/bin/env python3
"""
Repair XML Structure Script

Fixes broken FCP7 XML files generated by God Mode AI editor that have
incorrect hierarchy (<xmeml><project><children><sequence>) and converts
them to DaVinci Resolve-compatible format (<xmeml><sequence>).

Usage:
    python repair_xml_structure.py broken.xml repaired.xml

Author: EasyEdit v2
Date: 2025-11-27
"""

import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Optional


def validate_xml_structure(xml_path: Path) -> dict:
    """Validate XML structure and return diagnostics"""
    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()

        checks = {
            'has_xml_declaration': False,
            'has_doctype': False,
            'has_xmeml_root': root.tag == 'xmeml',
            'xmeml_version': root.get('version'),
            'has_project_wrapper': len(root.findall('.//project')) > 0,
            'has_children_wrapper': len(root.findall('.//children')) > 0,
            'has_direct_sequence': len(root.findall('./sequence')) > 0,
            'sequence_count': len(root.findall('.//sequence'))
        }

        # Check file content for declaration and doctype
        with open(xml_path, 'r', encoding='utf-8') as f:
            content = f.read(500)  # Check first 500 chars
            checks['has_xml_declaration'] = '<?xml version' in content
            checks['has_doctype'] = '<!DOCTYPE xmeml>' in content

        return checks
    except Exception as e:
        print(f"[ERROR] Failed to validate XML: {e}")
        return {}


def extract_sequence_from_broken_xml(xml_path: Path) -> Optional[ET.Element]:
    """Extract sequence element from broken XML structure"""
    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()

        # Try to find sequence element
        # Path 1: Direct child of xmeml (already correct)
        sequence = root.find('./sequence')
        if sequence is not None:
            print("[INFO] Sequence found as direct child - structure is already correct")
            return sequence

        # Path 2: Under project/children (broken structure)
        sequence = root.find('./project/children/sequence')
        if sequence is not None:
            print("[INFO] Sequence found under project/children - needs repair")
            return sequence

        # Path 3: Under children only
        sequence = root.find('./children/sequence')
        if sequence is not None:
            print("[INFO] Sequence found under children - needs repair")
            return sequence

        # Path 4: Anywhere in tree (fallback)
        sequence = root.find('.//sequence')
        if sequence is not None:
            print("[WARN] Sequence found in unexpected location - attempting repair")
            return sequence

        print("[ERROR] No sequence element found in XML")
        return None

    except Exception as e:
        print(f"[ERROR] Failed to parse XML: {e}")
        return None


def create_repaired_xml(sequence: ET.Element) -> str:
    """Create repaired XML with correct structure"""
    # Create new root with correct structure
    root = ET.Element('xmeml', version='5')
    root.append(sequence)

    # Convert to string
    rough_string = ET.tostring(root, encoding='unicode')

    # Pretty print (basic formatting)
    try:
        from xml.dom import minidom
        reparsed = minidom.parseString(rough_string)
        pretty = reparsed.toprettyxml(indent="  ")

        # Remove the first line (minidom adds its own XML declaration)
        lines = pretty.split('\n')[1:]
        pretty_content = '\n'.join(lines)

        # Add correct XML declaration and DOCTYPE
        xml_declaration = '<?xml version="1.0" encoding="UTF-8"?>\n'
        doctype = '<!DOCTYPE xmeml>\n'

        return xml_declaration + doctype + pretty_content

    except Exception as e:
        print(f"[WARN] Pretty printing failed: {e}, using basic format")
        # Fallback: basic format
        return f'<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE xmeml>\n{rough_string}'


def repair_xml_file(input_path: Path, output_path: Path) -> bool:
    """Repair XML file structure"""
    print(f"\n{'='*60}")
    print(f"XML Structure Repair Tool")
    print(f"{'='*60}\n")

    # Validate input file exists
    if not input_path.exists():
        print(f"[ERROR] Input file not found: {input_path}")
        return False

    print(f"[INFO] Input file: {input_path}")
    print(f"[INFO] Output file: {output_path}\n")

    # Validate input structure
    print("[STEP 1] Validating input XML structure...")
    checks = validate_xml_structure(input_path)

    if not checks:
        return False

    print(f"  - XML Declaration: {'[OK]' if checks['has_xml_declaration'] else '[X]'}")
    print(f"  - DOCTYPE: {'[OK]' if checks['has_doctype'] else '[X]'}")
    print(f"  - XMEML Root: {'[OK]' if checks['has_xmeml_root'] else '[X]'}")
    print(f"  - Version: {checks['xmeml_version']}")
    print(f"  - Project Wrapper: {'[X] (needs removal)' if checks['has_project_wrapper'] else '[OK] (none)'}")
    print(f"  - Children Wrapper: {'[X] (needs removal)' if checks['has_children_wrapper'] else '[OK] (none)'}")
    print(f"  - Direct Sequence: {'[OK]' if checks['has_direct_sequence'] else '[X]'}")
    print(f"  - Sequence Count: {checks['sequence_count']}\n")

    # Check if repair is needed
    if checks['has_direct_sequence'] and not checks['has_project_wrapper'] and not checks['has_children_wrapper']:
        print("[INFO] XML structure is already correct - no repair needed")
        print("[INFO] Copying file to output location...\n")
        with open(input_path, 'r', encoding='utf-8') as f_in:
            with open(output_path, 'w', encoding='utf-8') as f_out:
                f_out.write(f_in.read())
        return True

    # Extract sequence
    print("[STEP 2] Extracting sequence element...")
    sequence = extract_sequence_from_broken_xml(input_path)

    if sequence is None:
        return False

    print(f"  - Sequence ID: {sequence.get('id', 'N/A')}")
    print(f"  - Sequence Name: {sequence.find('./name').text if sequence.find('./name') is not None else 'N/A'}\n")

    # Create repaired XML
    print("[STEP 3] Creating repaired XML structure...")
    repaired_xml = create_repaired_xml(sequence)

    # Write output
    print(f"[STEP 4] Writing repaired XML to: {output_path}...")
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(repaired_xml)

    # Validate output
    print("\n[STEP 5] Validating repaired XML structure...")
    output_checks = validate_xml_structure(output_path)

    if not output_checks:
        return False

    print(f"  - XML Declaration: {'[OK]' if output_checks['has_xml_declaration'] else '[X]'}")
    print(f"  - DOCTYPE: {'[OK]' if output_checks['has_doctype'] else '[X]'}")
    print(f"  - XMEML Root: {'[OK]' if output_checks['has_xmeml_root'] else '[X]'}")
    print(f"  - Version: {output_checks['xmeml_version']}")
    print(f"  - Project Wrapper: {'[X] (ERROR)' if output_checks['has_project_wrapper'] else '[OK] (removed)'}")
    print(f"  - Children Wrapper: {'[X] (ERROR)' if output_checks['has_children_wrapper'] else '[OK] (removed)'}")
    print(f"  - Direct Sequence: {'[OK]' if output_checks['has_direct_sequence'] else '[X] (ERROR)'}")
    print(f"  - Sequence Count: {output_checks['sequence_count']}")

    # Final validation
    success = (
        output_checks['has_xml_declaration'] and
        output_checks['has_doctype'] and
        output_checks['has_xmeml_root'] and
        not output_checks['has_project_wrapper'] and
        not output_checks['has_children_wrapper'] and
        output_checks['has_direct_sequence']
    )

    print(f"\n{'='*60}")
    if success:
        print("[SUCCESS] XML structure repaired successfully!")
        print(f"[SUCCESS] Output file: {output_path}")
        print("[INFO] You can now import this XML to DaVinci Resolve")
    else:
        print("[FAILURE] XML repair failed - structure is not correct")
    print(f"{'='*60}\n")

    return success


def main():
    """Main entry point"""
    if len(sys.argv) != 3:
        print("Usage: python repair_xml_structure.py <input.xml> <output.xml>")
        print("\nExample:")
        print("  python repair_xml_structure.py broken.xml repaired.xml")
        sys.exit(1)

    input_path = Path(sys.argv[1])
    output_path = Path(sys.argv[2])

    success = repair_xml_file(input_path, output_path)
    sys.exit(0 if success else 1)


if __name__ == '__main__':
    main()
